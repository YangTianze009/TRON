"""
Cattell-style IQ series-completion. A 1-row strip of N=3-6 frames evolves
under 2-3 simultaneous rules (motion + rotation + count + shading + size);
the model picks the next frame from 4 candidates labeled A-D.

Targets the inductive pattern-induction gap on IQ-test style benchmarks
(British 11+ / Cattell scale / Raven's). Each frame is a small box with
a couple of simple shapes inside (squares, circles, triangles, dots),
and rules combine over time:
  - motion: shape drifts position each step (NW, N, NE, E, SE, S, SW, W)
  - rotation: shape rotates 45/90 degrees per step
  - count: extra small marker added/removed each step
  - shading: shape toggles black/white each step

Distractors are generated by:
  - applying the wrong subset of rules (one rule violated)
  - off-by-one count
  - flipped shading
  - flipped motion direction
"""
